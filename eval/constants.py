def _unique(items: Iterable[str]) -> set[str]:
    return {item.strip() for item in items if item and item.strip()}


def _dedup(pairs: Iterable[tuple[str, str]]) -> Dict[str, str]:
    deduped: Dict[str, str] = {}
    for key, value in pairs:
        deduped[key] = value
    return deduped


